#!/usr/bin/env bash
# Builds the Rust core for iPhone and the simulator and generates the Swift
# bindings for each.
#
# The core contains C: libgit2 (vendored by libgit2-sys) and ring's
# primitives. Compiling those for iOS needs the Apple SDK, so the iOS
# libraries are built on macOS only. On Linux this script still makes the
# host builds and both sets of Swift bindings, which is enough to check that
# the interface Swift sees is intact; pass --bindings-only to do the same on
# a Mac.
#
# Two builds of the core, by the `sim` cargo feature (design.md 5.5):
#
# - the simulator library has it: the simulated key, keystore, clock,
#   fixture store, git host and GitHub, which the simulator's UI tests drive;
# - the device library is built without it (`--no-default-features`), and
#   scripts/check-no-sim.sh proves the simulation is not in it (and, with
#   --expect on the simulator library, that its patterns would find it).
#
# Output, all under app/:
#   build/core/ios/libpaw_core.a          device library, no `sim` (macOS only)
#   build/core/ios-sim/libpaw_core.a      simulator library, `sim`  (macOS only)
#   build/core/device-headers/            device library's C header and module map
#   build/core/headers/                   simulator library's C header and module map
#   Generated/paw_core_device.swift       device bindings, `#if !targetEnvironment(simulator)`
#   Generated/paw_core.swift              simulator bindings, `#if targetEnvironment(simulator)`
#
# Each library's bindings come from a host build with the same features:
# UniFFI's Swift checks every exported function's checksum when it loads,
# so the simulator's bindings cannot be linked against the device library.
# Both bindings files are compiled into the app and the extension, each
# wrapped in the `#if` that matches the slice of the xcframework the build
# links (scripts/make-xcframework.sh), so a device build only ever sees the
# device bindings, whatever its configuration. Swift that names a Sim* type
# must be inside `#if targetEnvironment(simulator)` for the same reason.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/app/build/core"
gen="$root/app/Generated"

ios=yes
for arg in "$@"; do
  case "$arg" in
    --bindings-only) ios=no ;;
    *) echo "build-core: unknown option $arg" >&2; exit 2 ;;
  esac
done
if [[ "$ios" == yes && "$(uname -s)" != "Darwin" ]]; then
  echo "build-core: not on macOS, so no iOS libraries; generating the bindings only" >&2
  ios=no
fi

rm -rf "$out" "$gen"
mkdir -p "$out" "$gen"

# A separate target directory for the build without `sim`, so neither
# build makes the other recompile next time.
nosim=(--no-default-features --target-dir target/no-sim)

cd "$root/core"
if [[ "$ios" == yes ]]; then
  mkdir -p "$out/ios" "$out/ios-sim"
  # The C parts (libgit2, ring) otherwise target the newest SDK, not the
  # app's deployment target.
  IPHONEOS_DEPLOYMENT_TARGET="$(sed -nE 's/^ +iOS: "?([0-9.]+)"?$/\1/p' "$root/app/project.yml")"
  [[ -n "$IPHONEOS_DEPLOYMENT_TARGET" ]] || { echo "build-core: no iOS deployment target in app/project.yml" >&2; exit 2; }
  export IPHONEOS_DEPLOYMENT_TARGET
  cargo build --lib --release --target aarch64-apple-ios "${nosim[@]}"
  cargo build --lib --release --target aarch64-apple-ios-sim
  cp target/no-sim/aarch64-apple-ios/release/libpaw_core.a "$out/ios/"
  cp target/aarch64-apple-ios-sim/release/libpaw_core.a "$out/ios-sim/"
  "$root/scripts/check-no-sim.sh" "$out/ios/libpaw_core.a"
  "$root/scripts/check-no-sim.sh" --expect "$out/ios-sim/libpaw_core.a"
fi

bindings() {
  local lib="$1" swift="$2" headers="$3" condition="$4" which="$5" tmp="$out/bindings"
  rm -rf "$tmp" && mkdir -p "$tmp" "$headers"
  cargo run -q --features bindgen --bin uniffi-bindgen -- generate --library "$lib" --language swift --out-dir "$tmp"
  {
    echo "// Generated by scripts/build-core.sh: the core $which. Do not edit."
    echo "#if $condition"
    cat "$tmp/paw_core.swift"
    echo
    echo "#endif"
  } > "$swift"
  mv "$tmp/paw_coreFFI.h" "$headers/"
  mv "$tmp/paw_coreFFI.modulemap" "$headers/module.modulemap"
  rm -rf "$tmp"
}

cargo build --lib
cargo build --lib "${nosim[@]}"
"$root/scripts/check-no-sim.sh" target/no-sim/debug/libpaw_core.a
"$root/scripts/check-no-sim.sh" --expect target/debug/libpaw_core.a
bindings target/debug/libpaw_core.a "$gen/paw_core.swift" "$out/headers" \
  "targetEnvironment(simulator)" "with the sim feature, for the simulator"
bindings target/no-sim/debug/libpaw_core.a "$gen/paw_core_device.swift" "$out/device-headers" \
  "!targetEnvironment(simulator)" "without the sim feature, for devices"
